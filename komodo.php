    <p>
      Pulau Komodo merupakan salah satu destinasi wisata paling ikonik di Indonesia yang terletak di Provinsi Nusa Tenggara Timur. Pulau ini terkenal sebagai habitat asli hewan purba <strong>Komodo</strong>, reptil terbesar di dunia yang hanya dapat ditemukan di wilayah ini. Selain bertemu langsung dengan komodo, wisatawan juga dapat menikmati keindahan alam yang memukau, seperti bukit savana, pantai berpasir merah muda (Pink Beach), serta dunia bawah laut yang kaya dengan terumbu karang dan biota laut.
    </p>
    <p>
      Pulau ini termasuk dalam kawasan <em>Taman Nasional Komodo</em> yang telah diakui sebagai Situs Warisan Dunia oleh UNESCO. Aktivitas populer di sini antara lain trekking ke puncak bukit untuk melihat panorama pulau, snorkeling, diving, dan menjelajahi pulau-pulau sekitarnya dengan kapal.
