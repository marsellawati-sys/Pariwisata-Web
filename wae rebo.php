      Wae Rebo adalah sebuah desa adat tradisional yang terletak di ketinggian 1.200 meter di atas permukaan laut di Kabupaten Manggarai, Flores, Nusa Tenggara Timur. Dikenal sebagai <strong"desa di atas awan"></strong>, Wae Rebo menyuguhkan pesona alam yang luar biasa berpadu dengan kearifan lokal yang masih sangat terjaga.
    
Desa ini hanya memiliki tujuh rumah adat utama yang disebut Mbaru Niang, berbentuk kerucut dan terbuat dari bahan alami seperti ijuk dan bambu. Keunikan arsitekturnya telah membuat Wae Rebo mendapat penghargaan UNESCO untuk pelestarian budaya.
    </p> 
